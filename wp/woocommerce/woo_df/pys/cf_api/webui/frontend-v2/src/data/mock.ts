export function recordsForZone(zone: string): DnsRecord[] {
  if (recordsByZone[zone]) return recordsByZone[zone];
  return baseRecords.map((r) => ({
    ...r,
    id: `${r.id}-${zone}`,
    name: r.name.replace("example.com", zone),
  }));
}

